// Builds src/styles/tokens.css from tokens/tokens.json.
// Primitives become --p-* variables; semantic tokens reference them and
// resolve per theme (light by default, dark under [data-theme="dark"]).
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync(new URL('../tokens/tokens.json', import.meta.url), 'utf8'));
const lines = [];
const flat = (group, prefix) =>
  Object.entries(group).map(([k, v]) => `  --p-${prefix}-${k}: ${v};`);

const ref = (value) =>
  value.replace(/\{(\w+)\.([\w-]+)\}/g, (_, group, key) => {
    if (!tokens.primitive[group]?.[key]) throw new Error(`Unknown token reference: ${value}`);
    return `var(--p-${group}-${key})`;
  });

const semantic = (theme) =>
  Object.entries(tokens.semantic[theme]).map(([k, v]) => `  --${k}: ${ref(v)};`);

lines.push('/* Generated by scripts/build-tokens.mjs. Edit tokens/tokens.json instead. */');
lines.push(':root {');
for (const [group, values] of Object.entries(tokens.primitive)) lines.push(...flat(values, group));
lines.push('', '  /* semantic · light */', ...semantic('light'));
lines.push('}', '');
lines.push(':root[data-theme="dark"] {', ...semantic('dark'), '}', '');

writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), lines.join('\n'));
console.log('tokens.css written');
